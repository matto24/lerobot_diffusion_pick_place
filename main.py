"""Watch one scripted expert episode in the MuJoCo viewer.

    uv run mjpython main.py      # macOS (the passive viewer needs mjpython)
    uv run python main.py        # Linux / Windows
"""

import time

import mujoco
import mujoco.viewer
import numpy as np

from scripts.box_movement_example import program
from src.paths import STANDARD_SCENE_PATH
from src.robot import hande_ctrl_qpos, ur_ctrl_qpos, ur_set_qpos

HOME_Q = np.array([0, -np.pi / 2, np.pi / 2, -np.pi / 2, -np.pi / 2, 0])

if __name__ == "__main__":
    m = mujoco.MjModel.from_xml_path(str(STANDARD_SCENE_PATH))
    d = mujoco.MjData(m)

    with mujoco.viewer.launch_passive(m, d) as viewer:
        ur_set_qpos(d, HOME_Q)
        hande_ctrl_qpos(d, 0)  # open gripper

        # Let the scene settle for a moment before planning.
        settle_until = time.time() + 1.0
        while time.time() < settle_until:
            mujoco.mj_step(m, d)
            viewer.sync()

        cmd_queue = program(d, m)  # one (joint target, gripper) command per physics step
        print(f"{len(cmd_queue)} commands generated by the expert")

        step = 0
        while viewer.is_running():
            if step < len(cmd_queue):
                desired_q, gripper_value = cmd_queue[step]
                if isinstance(desired_q, np.ndarray):
                    ur_ctrl_qpos(d, desired_q)
                if gripper_value is not None:
                    hande_ctrl_qpos(d, gripper_value)
                step += 1
            mujoco.mj_step(m, d)
            viewer.sync()
